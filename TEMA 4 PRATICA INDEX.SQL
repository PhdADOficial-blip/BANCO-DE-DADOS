FROM TIPO_DOCUMENTO TD
INNER JOIN DOCUMENTO D ON D.TIPO = TD.NR
INNER JOIN DESPACHO DP ON DP.DOCUMENTO = D.NUMERO 
INNER JOIN TIPO_DESPACHO TDP ON DP.TIPO = TDP.NR

